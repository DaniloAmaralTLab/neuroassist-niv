// trn.model.ts — domain types for the TRN AI-Assisted Training module.
// Source: BE api-contract.md (trn-service, port 8089), SPEC-03 view models,
// SPEC-04 data access, ADR-002 dual-authorization, ADR-005 single-identity.
// English-only product (ADR-018-english-only-product).

// ---------------------------------------------------------------------------
// Locale
// ---------------------------------------------------------------------------

/** English is the only supported locale (ADR-018). */
export type Locale = 'en';

// ---------------------------------------------------------------------------
// Proposal lifecycle (ADR-003 + BE api-contract §3)
// ---------------------------------------------------------------------------

export type ProposalStatus =
  | 'draft'
  | 'proposed'
  | 'caregiver_approved'
  | 'patient_approved'
  | 'approved'          // both halves done — synthesis may start
  | 'synthesizing'
  | 'indexed'
  | 'published'
  | 'rejected'
  | 'withdrawn'
  | 'erased';

// ---------------------------------------------------------------------------
// Authorization value object (ADR-002 — dual authorization)
// ---------------------------------------------------------------------------

/**
 * Dual Authorization record embedded in a Proposal.
 * Both halves are attested under the caregiver's JWT (trn.proposal.approve).
 * ACS INV-3 forbids a patient-session token on any /trn path.
 * There is NO trn.proposal.confirm authority — only trn.proposal.approve (BE §4).
 */
export interface ProposalAuthorization {
  caregiverConfirmed: boolean;
  caregiverConfirmedAt: string | null;
  /** Patient / guardian assent attested in-session by the caregiver (ADR-002, Option C). */
  patientAssented: boolean;
  patientAssentedAt: string | null;
  /** Relationship of the attesting person to the patient (e.g. "spouse", "clinic nurse"). */
  relationship: string | null;
  /** Evidence reference (photo/signature path) stored server-side. */
  evidenceRef: string | null;
}

// ---------------------------------------------------------------------------
// Proposal (BE §3 / SPEC-03 §1)
// ---------------------------------------------------------------------------

export interface Proposal {
  id: string;
  sessionId: string;
  /** Proposed phrase text (English only). */
  text: string;
  /** Suggested parent category ID (or null for root). */
  parentId: string | null;
  status: ProposalStatus;
  authorization: ProposalAuthorization;
  /** Audio asset ID returned after synthesis — null until BE synthesizes. */
  audioAssetId: string | null;
  createdAt: string;
  updatedAt: string;
}

// ---------------------------------------------------------------------------
// Training Session (BE §2 / SPEC-03 §2)
// ---------------------------------------------------------------------------

export type SessionStatus = 'open' | 'ended';

export interface TrainingSession {
  id: string;
  patientId: string;
  status: SessionStatus;
  proposals: Proposal[];
  startedAt: string;
  endedAt: string | null;
}

// ---------------------------------------------------------------------------
// Dialog (BE §3.1 — LLM turn via trn-service; never a direct vendor call)
// ---------------------------------------------------------------------------

export interface DialogMessage {
  role: 'assistant' | 'caregiver';
  content: string;
  timestamp: string;
}

export interface DialogTurnResult {
  messages: DialogMessage[];
  /** New proposals generated by the LLM turn — appended to the session. */
  newProposals: Proposal[];
}

// ---------------------------------------------------------------------------
// Consent (BE §5 / ADR-005 TTS consent)
// ---------------------------------------------------------------------------

export type ConsentStatus = 'granted' | 'revoked' | 'not_captured';

export interface ConsentRecord {
  id: string;
  patientId: string;
  status: ConsentStatus;
  grantedAt: string | null;
  revokedAt: string | null;
}

// ---------------------------------------------------------------------------
// Publication (BE §6 — async publish lifecycle)
// ---------------------------------------------------------------------------

export type PublicationStatus = 'pending' | 'published' | 'failed';

export interface Publication {
  id: string;
  proposalId: string;
  status: PublicationStatus;
  requestedAt: string;
  publishedAt: string | null;
  failureReason: string | null;
}

// ---------------------------------------------------------------------------
// Erasure (BE §7)
// ---------------------------------------------------------------------------

export interface ErasureAck {
  patientId: string;
  erasedCount: number;
  retiredCount: number;
  requestedAt: string;
}

// ---------------------------------------------------------------------------
// Wire shapes (mirror BE JSON — used by HTTP adapters only)
// ---------------------------------------------------------------------------

/** Wire representation of ProposalAuthorization from BE. */
export interface AuthorizationWire {
  caregiverConfirmed: boolean;
  caregiverConfirmedAt: string | null;
  patientAssented: boolean;
  patientAssentedAt: string | null;
  relationship: string | null;
  evidenceRef: string | null;
}

/** Wire representation of Proposal from BE (§3). */
export interface ProposalWire {
  id: string;
  sessionId: string;
  text: string;
  parentId: string | null;
  status: ProposalStatus;
  authorization: AuthorizationWire;
  audioAssetId: string | null;
  createdAt: string;
  updatedAt: string;
}

/** Wire representation of TrainingSession from BE (§2). */
export interface TrainingSessionWire {
  id: string;
  patientId: string;
  status: SessionStatus;
  proposals: ProposalWire[];
  startedAt: string;
  endedAt: string | null;
}

/** Wire representation of a dialog turn response (§3.1). */
export interface DialogTurnWire {
  messages: DialogMessage[];
  newProposals: ProposalWire[];
}

/** Wire representation of ConsentRecord (§5). */
export interface ConsentWire {
  id: string;
  patientId: string;
  status: ConsentStatus;
  grantedAt: string | null;
  revokedAt: string | null;
}

/** Wire representation of Publication (§6). */
export interface PublicationWire {
  id: string;
  proposalId: string;
  status: PublicationStatus;
  requestedAt: string;
  publishedAt: string | null;
  failureReason: string | null;
}

/** Wire representation of ErasureAck (§7). */
export interface ErasureAckWire {
  patientId: string;
  erasedCount: number;
  retiredCount: number;
  requestedAt: string;
}

// ---------------------------------------------------------------------------
// Domain mappers (wire → domain; shared by HTTP and Mock adapters)
// ---------------------------------------------------------------------------

export function toAuthorization(w: AuthorizationWire): ProposalAuthorization {
  return {
    caregiverConfirmed: w.caregiverConfirmed,
    caregiverConfirmedAt: w.caregiverConfirmedAt,
    patientAssented: w.patientAssented,
    patientAssentedAt: w.patientAssentedAt,
    relationship: w.relationship,
    evidenceRef: w.evidenceRef,
  };
}

export function toProposal(w: ProposalWire): Proposal {
  return {
    id: w.id,
    sessionId: w.sessionId,
    text: w.text,
    parentId: w.parentId,
    status: w.status,
    authorization: toAuthorization(w.authorization),
    audioAssetId: w.audioAssetId,
    createdAt: w.createdAt,
    updatedAt: w.updatedAt,
  };
}

export function toSession(w: TrainingSessionWire): TrainingSession {
  return {
    id: w.id,
    patientId: w.patientId,
    status: w.status,
    proposals: w.proposals.map(toProposal),
    startedAt: w.startedAt,
    endedAt: w.endedAt,
  };
}

export function toConsent(w: ConsentWire): ConsentRecord {
  return {
    id: w.id,
    patientId: w.patientId,
    status: w.status,
    grantedAt: w.grantedAt,
    revokedAt: w.revokedAt,
  };
}

export function toPublication(w: PublicationWire): Publication {
  return {
    id: w.id,
    proposalId: w.proposalId,
    status: w.status,
    requestedAt: w.requestedAt,
    publishedAt: w.publishedAt,
    failureReason: w.failureReason,
  };
}

export function toErasureAck(w: ErasureAckWire): ErasureAck {
  return {
    patientId: w.patientId,
    erasedCount: w.erasedCount,
    retiredCount: w.retiredCount,
    requestedAt: w.requestedAt,
  };
}
